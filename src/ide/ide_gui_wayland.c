static long long now_ms(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (long long)ts.tv_sec * 1000 + ts.tv_nsec / 1000000;
}

/* fontconfig substitutes instead of failing, so a family is installed only
 * if the match has that very name. Its file into *path (malloc'ed). */
static int font_file(const char* name, char** path)
{
    FcPattern* pat = FcNameParse((const FcChar8*)name);
    if (!pat)
        return 0;
    FcPatternAddInteger(pat, FC_SPACING, FC_MONO);
    FcConfigSubstitute(NULL, pat, FcMatchPattern);
    FcDefaultSubstitute(pat);
    FcResult result;
    FcPattern* match = FcFontMatch(NULL, pat, &result);
    FcPatternDestroy(pat);
    if (!match)
        return 0;
    FcChar8* family = NULL;
    FcChar8* file = NULL;
    int ok = FcPatternGetString(match, FC_FAMILY, 0, &family) == FcResultMatch &&
             FcPatternGetString(match, FC_FILE, 0, &file) == FcResultMatch &&
             (strcasecmp((const char*)family, name) == 0 || strcmp(name, "Monospace") == 0);
    if (ok && path)
        *path = strdup((const char*)file);
    FcPatternDestroy(match);
    return ok;
}

static void font_free(struct font* f)
{
    for (int i = 0; i < f->cap; i++)
        free(f->glyphs[i].alpha);
    free(f->glyphs);
    if (f->face)
        FT_Done_Face(f->face);
    memset(f, 0, sizeof *f);
}

static int font_open(struct gui_canvas* c, struct font* f, int pt)
{
    const char* family = c->family;
    char* path = NULL;
    for (int i = 0; !family && i < CANDIDATE_COUNT; i++)
    {
        if (font_file(font_candidates[i], NULL))
            family = font_candidates[i];
    }
    if (!family || !font_file(family, &path))
        return 0;
    FT_Face face;
    int err = FT_New_Face(c->ft, path, 0, &face);
    free(path);
    if (err)
        return 0;
    FT_Set_Char_Size(face, 0, pt * 64, (FT_UInt)DPI, (FT_UInt)DPI);
    memset(f, 0, sizeof *f);
    f->face = face;
    int adv = 0;
    if (FT_Load_Char(face, 'M', FT_LOAD_DEFAULT) == 0)
        adv = (int)((face->glyph->advance.x + 32) >> 6);
    int ascent = (int)((face->size->metrics.ascender + 63) >> 6);
    int descent = (int)((-face->size->metrics.descender + 63) >> 6);
    f->metrics.cell_w = adv > 0 ? adv : 1;
    f->metrics.cell_h = ascent + descent > 0 ? ascent + descent : 1;
    f->metrics.ascent = ascent;
    return 1;
}

static const struct glyph* font_glyph(struct font* f, uint32_t cp)
{
    if (f->count * 2 >= f->cap)
    {
        int cap = f->cap ? f->cap * 2 : 256;
        struct glyph* g = calloc((size_t)cap, sizeof *g);
        if (!g)
            abort();
        for (int i = 0; i < f->cap; i++)
        {
            if (!f->glyphs[i].cp)
                continue;
            int k = (int)(f->glyphs[i].cp * 2654435761u % (unsigned)cap);
            while (g[k].cp)
                k = (k + 1) % cap;
            g[k] = f->glyphs[i];
        }
        free(f->glyphs);
        f->glyphs = g;
        f->cap = cap;
    }
    int k = (int)(cp * 2654435761u % (unsigned)f->cap);
    while (f->glyphs[k].cp && f->glyphs[k].cp != cp)
        k = (k + 1) % f->cap;
    struct glyph* g = &f->glyphs[k];
    if (g->cp == cp)
        return g;
    g->cp = cp;
    f->count++;
    FT_UInt index = FT_Get_Char_Index(f->face, cp);
    if (!index || FT_Load_Glyph(f->face, index, FT_LOAD_DEFAULT) ||
        FT_Render_Glyph(f->face->glyph, FT_RENDER_MODE_NORMAL))
        return g;   /* not in the font: nothing drawn */
    FT_Bitmap* bm = &f->face->glyph->bitmap;
    g->left = f->face->glyph->bitmap_left;
    g->top = f->face->glyph->bitmap_top;
    g->w = (int)bm->width;
    g->h = (int)bm->rows;
    if (g->w > 0 && g->h > 0)
    {
        g->alpha = malloc((size_t)g->w * (size_t)g->h);
        if (g->alpha)
        {
            for (int y = 0; y < g->h; y++)
                memcpy(g->alpha + y * g->w, bm->buffer + y * bm->pitch, (size_t)g->w);
        }
    }
    return g;
}

static void offer_fonts(struct wl_window* win)
{
    const char* names[CANDIDATE_COUNT];
    win->font_count = 0;
    for (int i = 0; i < CANDIDATE_COUNT; i++)
    {
        if (!font_file(font_candidates[i], NULL))
            continue;
        names[win->font_count] = font_candidates[i];
        win->offered_fonts[win->font_count++] = i;
    }
    gui_app_set_fonts(win->app, names, win->font_count, 0);
}

/* (Re)creates both fonts from canvas->pt: they always exist together. */
static int apply_font(struct gui_canvas* c)
{
    int small_pt = (c->pt * SMALL_FONT_PERCENT + 50) / 100;
    struct font main, small_font;
    if (!font_open(c, &main, c->pt))
        return 0;
    if (!font_open(c, &small_font, small_pt > 0 ? small_pt : 1))
    {
        font_free(&main);
        return 0;
    }
    font_free(&c->main);
    font_free(&c->small_font);
    c->main = main;
    c->small_font = small_font;
    return 1;
}

/* --- Drawing primitives (ide_gui_backend.h): pixels, by hand --- */

struct gui_metrics gui_font_metrics(struct gui_canvas* c, enum gui_font font)
{
    return font == GUI_FONT_SMALL ? c->small_font.metrics : c->main.metrics;
}

int gui_scrollbar_size(struct gui_canvas* c)
{
    int size = (10 * c->pt + DEFAULT_FONT_PT / 2) / DEFAULT_FONT_PT;
    return size > 2 ? size : 2;
}

void gui_set_clip(struct gui_canvas* c, int x, int y, int w, int h)
{
    c->clip_on = w > 0 && h > 0;
    c->cx = x;
    c->cy = y;
    c->cw = w;
    c->ch = h;
}

/* The rect inside the canvas and the clip; 0 if nothing is left. */
static int clip_rect(const struct gui_canvas* c, int* x, int* y, int* w, int* h)
{
    int x0 = *x, y0 = *y, x1 = *x + *w, y1 = *y + *h;
    if (c->clip_on)
    {
        if (x0 < c->cx) x0 = c->cx;
        if (y0 < c->cy) y0 = c->cy;
        if (x1 > c->cx + c->cw) x1 = c->cx + c->cw;
        if (y1 > c->cy + c->ch) y1 = c->cy + c->ch;
    }
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 > c->w) x1 = c->w;
    if (y1 > c->h) y1 = c->h;
    *x = x0;
    *y = y0;
    *w = x1 - x0;
    *h = y1 - y0;
    return *w > 0 && *h > 0;
}

void gui_fill_rect(struct gui_canvas* c, int x, int y, int w, int h, uint32_t rgb)
{
    if (!clip_rect(c, &x, &y, &w, &h))
        return;
    uint32_t px = 0xFF000000u | (rgb & 0xFFFFFF);
    for (int row = 0; row < h; row++)
    {
        uint32_t* p = c->pixels + (size_t)(y + row) * (size_t)c->w + (size_t)x;
        for (int i = 0; i < w; i++)
            p[i] = px;
    }
}

void gui_shade_rect(struct gui_canvas* c, int x, int y, int w, int h, int alpha)
{
    if (!clip_rect(c, &x, &y, &w, &h))
        return;
    unsigned keep = 255u - (unsigned)alpha;
    for (int row = 0; row < h; row++)
    {
        uint32_t* p = c->pixels + (size_t)(y + row) * (size_t)c->w + (size_t)x;
        for (int i = 0; i < w; i++)
        {
            uint32_t v = p[i];
            uint32_t r = ((v >> 16) & 0xFF) * keep / 255, g = ((v >> 8) & 0xFF) * keep / 255, b = (v & 0xFF) * keep / 255;
            p[i] = 0xFF000000u | r << 16 | g << 8 | b;
        }
    }
}

void gui_draw_text(struct gui_canvas* c, int x, int y, const uint32_t* cps, int count,
                   uint32_t fg, uint32_t bg, enum gui_font font)
{
    struct font* f = font == GUI_FONT_SMALL ? &c->small_font : &c->main;
    const struct gui_metrics* m = &f->metrics;
    gui_fill_rect(c, x, y, count * m->cell_w, m->cell_h, bg);
    /* the glyphs stay inside the run's rect, as the backend contract says */
    int rx = x, ry = y, rw = count * m->cell_w, rh = m->cell_h;
    if (!clip_rect(c, &rx, &ry, &rw, &rh))
        return;
    unsigned fr = (fg >> 16) & 0xFF, fgg = (fg >> 8) & 0xFF, fb = fg & 0xFF;
    for (int i = 0; i < count; i++)
    {
        uint32_t cp = cps[i];
        if (cp == ' ' || cp == 0)
            continue;
        const struct glyph* g = font_glyph(f, cp);
        if (!g->alpha)
            continue;
        int gx = x + i * m->cell_w + g->left;
        int gy = y + m->ascent - g->top;
        for (int row = 0; row < g->h; row++)
        {
            int py = gy + row;
            if (py < ry || py >= ry + rh)
                continue;
            uint32_t* line = c->pixels + (size_t)py * (size_t)c->w;
            const unsigned char* a = g->alpha + row * g->w;
            for (int col = 0; col < g->w; col++)
            {
                int px = gx + col;
                unsigned k = a[col];
                if (!k || px < rx || px >= rx + rw)
                    continue;
                uint32_t v = line[px];
                unsigned r = (fr * k + ((v >> 16) & 0xFF) * (255 - k)) / 255;
                unsigned gg = (fgg * k + ((v >> 8) & 0xFF) * (255 - k)) / 255;
                unsigned b = (fb * k + (v & 0xFF) * (255 - k)) / 255;
                line[px] = 0xFF000000u | r << 16 | gg << 8 | b;
            }
        }
    }
}

/* --- Buffers: the canvas, and the compositor's copies of it --- */

static void unite(struct gui_rect* r, const struct gui_rect* add)
{
    if (add->w <= 0 || add->h <= 0)
        return;
    if (r->w <= 0 || r->h <= 0)
    {
        *r = *add;
        return;
    }
    int x1 = r->x + r->w > add->x + add->w ? r->x + r->w : add->x + add->w;
    int y1 = r->y + r->h > add->y + add->h ? r->y + r->h : add->y + add->h;
    r->x = r->x < add->x ? r->x : add->x;
    r->y = r->y < add->y ? r->y : add->y;
    r->w = x1 - r->x;
    r->h = y1 - r->y;
}

static void buffer_release(void* data, struct wl_buffer* buffer)
{
    (void)buffer;
    struct shm_buffer* b = data;
    b->busy = 0;
}

static const struct wl_buffer_listener buffer_listener = { buffer_release };

static void buffer_destroy(struct shm_buffer* b)
{
    if (b->buffer)
        wl_buffer_destroy(b->buffer);
    if (b->pixels)
        munmap(b->pixels, b->size);
    memset(b, 0, sizeof *b);
}

static int buffer_create(struct wl_window* win, struct shm_buffer* b, int w, int h)
{
    int stride = w * 4;
    size_t size = (size_t)stride * (size_t)h;
    int fd = memfd_create("cakeide", MFD_CLOEXEC);
    if (fd < 0 || ftruncate(fd, (off_t)size) < 0)
    {
        if (fd >= 0)
            close(fd);
        return 0;
    }
    void* data = mmap(NULL, size, PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
    if (data == MAP_FAILED)
    {
        close(fd);
        return 0;
    }
    struct wl_shm_pool* pool = wl_shm_create_pool(win->shm, fd, (int32_t)size);
    b->buffer = wl_shm_pool_create_buffer(pool, 0, w, h, stride, WL_SHM_FORMAT_XRGB8888);
    wl_shm_pool_destroy(pool);
    close(fd);
    b->pixels = data;
    b->size = size;
    b->w = w;
    b->h = h;
    b->busy = 0;
    b->stale = (struct gui_rect){ 0, 0, w, h };   /* a new buffer: all of it to fill */
    wl_buffer_add_listener(b->buffer, &buffer_listener, b);
    return 1;
}

/* The canvas at the new size; its old contents are lost, so the core paints
 * everything next. */
static void resize_canvas(struct wl_window* win, int w, int h)
{
    struct gui_canvas* c = &win->canvas;
    if (w < 1) w = 1;
    if (h < 1) h = 1;
    if (c->pixels && w == c->w && h == c->h)
        return;
    free(c->pixels);
    c->pixels = calloc((size_t)w * (size_t)h, 4);
    if (!c->pixels)
        abort();
    c->w = w;
    c->h = h;
    for (int i = 0; i < 2; i++)
        buffer_destroy(&win->buffers[i]);   /* made again at the new size when needed */
    if (win->app)
    {
        gui_app_resize(win->app, w, h);
        gui_app_invalidate(win->app);
    }
}

/* What changed goes to a free buffer, which is handed to the compositor.
 * Each buffer remembers what changed since it was last filled, so only
 * that is copied into it - not the whole window. */
static void present(struct wl_window* win)
{
    struct gui_canvas* c = &win->canvas;
    if (!win->configured || win->damage.w <= 0)
        return;
    struct shm_buffer* b = NULL;
    for (int i = 0; i < 2 && !b; i++)
    {
        if (!win->buffers[i].busy)
            b = &win->buffers[i];
    }
    if (!b)
    {
        win->frame_pending = 1;   /* shown when the compositor gives one back */
        return;
    }
    if (!b->buffer && !buffer_create(win, b, c->w, c->h))
        return;
    for (int i = 0; i < 2; i++)
        unite(&win->buffers[i].stale, &win->damage);
    struct gui_rect s = b->stale;
    for (int row = s.y; row < s.y + s.h && row < c->h; row++)
        memcpy(b->pixels + (size_t)row * (size_t)c->w + (size_t)s.x,
               c->pixels + (size_t)row * (size_t)c->w + (size_t)s.x, (size_t)s.w * 4);
    b->stale = (struct gui_rect){ 0, 0, 0, 0 };
    b->busy = 1;
    wl_surface_attach(win->surface, b->buffer, 0, 0);
    wl_surface_damage_buffer(win->surface, win->damage.x, win->damage.y, win->damage.w, win->damage.h);
    wl_surface_commit(win->surface);
    win->damage = (struct gui_rect){ 0, 0, 0, 0 };
    win->frame_pending = 0;
}

static void set_cursor(struct wl_window* win, enum gui_cursor cursor);

/* Applies what the app asked for (quit, timer, font, zoom), lets the core
 * paint whatever changed and shows it. */
static void refresh(struct wl_window* win)
{
    struct gui_canvas* c = &win->canvas;
    if (gui_app_should_quit(win->app))
    {
        win->running = 0;
        return;
    }
    int ms;
    if (gui_app_take_timer(win->app, &ms))
    {
        win->timer_ms = ms > 0 ? ms : 0;
        win->timer_due = now_ms() + win->timer_ms;
    }
    int family = gui_app_take_font(win->app);
    if (family >= 0 && family < win->font_count)
    {
        c->family = font_candidates[win->offered_fonts[family]];
        if (apply_font(c))
            gui_app_font_changed(win->app, c);
    }
    int zoom = gui_app_take_zoom(win->app);
    if (zoom)
    {
        int pt = c->pt + zoom;
        c->pt = pt < 6 ? 6 : pt > 40 ? 40 : pt;
        if (apply_font(c))
            gui_app_font_changed(win->app, c);
    }
    if (!win->configured)
        return;
    struct gui_rect r;
    if (gui_app_paint(win->app, c, &r))
        unite(&win->damage, &r);
    present(win);
    set_cursor(win, gui_app_cursor(win->app));
}

/* The event to the app; the paint waits until every queued event is taken
 * (the main loop), so a burst costs one frame. */
static void post(struct wl_window* win, const struct gui_event* ev)
{
    gui_app_event(win->app, ev);
    win->pending = 1;
}

/* --- Clipboard (ide_gui_backend.h): the selection of wl_data_device --- */

#define TEXT_MIME "text/plain;charset=utf-8"

static void source_target(void* data, struct wl_data_source* s, const char* mime)
{
    (void)data; (void)s; (void)mime;
}

static void source_send(void* data, struct wl_data_source* s, const char* mime, int32_t fd)
{
    (void)s; (void)mime;
    struct wl_window* win = data;
    const char* text = win->canvas.clip_text ? win->canvas.clip_text : "";
    size_t len = strlen(text), done = 0;
    while (done < len)
    {
        ssize_t n = write(fd, text + done, len - done);
        if (n <= 0)
            break;
        done += (size_t)n;
    }
    close(fd);
}

static void source_cancelled(void* data, struct wl_data_source* s)
{
    struct wl_window* win = data;
    wl_data_source_destroy(s);
    if (win->source == s)
        win->source = NULL;
}

static const struct wl_data_source_listener source_listener = {
    .target = source_target,
    .send = source_send,
    .cancelled = source_cancelled,
};

void gui_clipboard_set(struct gui_canvas* c, const char* utf8)
{
    struct wl_window* win = c->win;
    free(c->clip_text);
    c->clip_text = strdup(utf8);
    if (!win->data_manager || !win->data_device)
        return;
    if (win->source)
        wl_data_source_destroy(win->source);
    win->source = wl_data_device_manager_create_data_source(win->data_manager);
    wl_data_source_offer(win->source, TEXT_MIME);
    wl_data_source_offer(win->source, "text/plain");
    wl_data_source_offer(win->source, "UTF8_STRING");
    wl_data_source_add_listener(win->source, &source_listener, win);
    wl_data_device_set_selection(win->data_device, win->source, win->serial);
}

char* gui_clipboard_get(struct gui_canvas* c)
{
    struct wl_window* win = c->win;
    if (win->source && c->clip_text)
        return strdup(c->clip_text);   /* ours: no round trip through the compositor */
    if (!win->selection_offer)
        return NULL;
    int fds[2];
    if (pipe(fds) != 0)
        return NULL;
    wl_data_offer_receive(win->selection_offer, TEXT_MIME, fds[1]);
    close(fds[1]);
    wl_display_flush(win->display);
    size_t len = 0, cap = 4096;
    char* text = malloc(cap + 1);
    /* the other client writes it; up to 1 s */
    for (;;)
    {
        struct pollfd p = { fds[0], POLLIN, 0 };
        if (poll(&p, 1, 1000) <= 0)
            break;
        if (text && len + 4096 > cap)
        {
            char* bigger = realloc(text, cap * 2 + 1);
            if (!bigger)
                break;
            text = bigger;
            cap *= 2;
        }
        ssize_t n = read(fds[0], text + len, cap - len);
        if (n <= 0)
            break;
        len += (size_t)n;
    }
    close(fds[0]);
    if (!text)
        return NULL;
    size_t o = 0;
    for (size_t i = 0; i < len; i++)
    {
        if (text[i] != '\r')   /* "\r\n" from other programs back to '\n' */
            text[o++] = text[i];
    }
    text[o] = '\0';
    return text;
}

