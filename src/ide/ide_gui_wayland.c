/* Waits for the compositor, the app's timer or the key repeat. */
static void wait_event(struct wl_window* win)
{
    while (wl_display_prepare_read(win->display) != 0)
        wl_display_dispatch_pending(win->display);
    wl_display_flush(win->display);
    long long due = -1;
    if (win->timer_ms > 0)
        due = win->timer_due;
    if (win->repeat_key && (due < 0 || win->repeat_due < due))
        due = win->repeat_due;
    int timeout = -1;
    if (due >= 0)
    {
        long long left = due - now_ms();
        timeout = left > 0 ? (int)left : 0;
    }
    struct pollfd p = { wl_display_get_fd(win->display), POLLIN, 0 };
    if (poll(&p, 1, timeout) > 0)
        wl_display_read_events(win->display);
    else
        wl_display_cancel_read(win->display);
    wl_display_dispatch_pending(win->display);
}

int main(int argc, char** argv)
{
    setlocale(LC_ALL, "");

    struct wl_window win = { 0 };
    struct gui_canvas* c = &win.canvas;
    c->win = &win;
    win.display = wl_display_connect(NULL);
    if (!win.display)
    {
        fprintf(stderr, "cannot connect to the Wayland display\n");
        return 1;
    }
    win.registry = wl_display_get_registry(win.display);
    wl_registry_add_listener(win.registry, &registry_listener, &win);
    wl_display_roundtrip(win.display);
    if (!win.compositor || !win.shm || !win.wm_base)
    {
        fprintf(stderr, "the compositor lacks wl_compositor, wl_shm or xdg_wm_base\n");
        return 1;
    }
    win.xkb = xkb_context_new(XKB_CONTEXT_NO_FLAGS);
    const char* locale = getenv("LC_ALL");
    if (!locale || !*locale) locale = getenv("LC_CTYPE");
    if (!locale || !*locale) locale = getenv("LANG");
    if (!locale || !*locale) locale = "C";
    win.compose_table = xkb_compose_table_new_from_locale(win.xkb, locale, XKB_COMPOSE_COMPILE_NO_FLAGS);
    if (win.compose_table)
        win.compose = xkb_compose_state_new(win.compose_table, XKB_COMPOSE_STATE_NO_FLAGS);
    if (win.seat && win.data_manager)
    {
        win.data_device = wl_data_device_manager_get_data_device(win.data_manager, win.seat);
        wl_data_device_add_listener(win.data_device, &device_listener, &win);
    }

    FcInit();
    if (FT_Init_FreeType(&c->ft))
    {
        fprintf(stderr, "cannot start FreeType\n");
        return 1;
    }
    c->pt = DEFAULT_FONT_PT;
    if (!apply_font(c))
    {
        fprintf(stderr, "no usable font (is fontconfig installed?)\n");
        return 1;
    }
    resize_canvas(&win, DEFAULT_COLS * c->main.metrics.cell_w, DEFAULT_ROWS * c->main.metrics.cell_h);

    win.surface = wl_compositor_create_surface(win.compositor);
    win.xdg_surface = xdg_wm_base_get_xdg_surface(win.wm_base, win.surface);
    xdg_surface_add_listener(win.xdg_surface, &xdg_surface_listener, &win);
    win.toplevel = xdg_surface_get_toplevel(win.xdg_surface);
    xdg_toplevel_add_listener(win.toplevel, &toplevel_listener, &win);
    xdg_toplevel_set_title(win.toplevel, "Cake " CAKE_VERSION);
    xdg_toplevel_set_app_id(win.toplevel, "cakeide");
    if (win.decoration_manager)
    {
        /* the compositor's title bar and borders, where it draws them */
        struct zxdg_toplevel_decoration_v1* deco =
            zxdg_decoration_manager_v1_get_toplevel_decoration(win.decoration_manager, win.toplevel);
        zxdg_toplevel_decoration_v1_set_mode(deco, ZXDG_TOPLEVEL_DECORATION_V1_MODE_SERVER_SIDE);
    }
    const char* size = getenv("XCURSOR_SIZE");
    win.cursor_theme = wl_cursor_theme_load(getenv("XCURSOR_THEME"), size && atoi(size) > 0 ? atoi(size) : 24, win.shm);
    win.cursor_surface = wl_compositor_create_surface(win.compositor);
    wl_surface_commit(win.surface);   /* the first configure answers this */

    win.app = gui_app_create();
    offer_fonts(&win);
    gui_app_start(win.app, c, argc, argv);
    gui_app_resize(win.app, c->w, c->h);
    win.running = 1;
    wl_display_roundtrip(win.display);

    while (win.running)
    {
        if (win.pending)
        {
            win.pending = 0;
            refresh(&win);   /* once for everything taken */
            if (!win.running)
                break;
        }
        wait_event(&win);
        if (wl_display_get_error(win.display))
            break;   /* the compositor went away */
        long long now = now_ms();
        if (win.timer_ms > 0 && now >= win.timer_due)
        {
            win.timer_due = now + win.timer_ms;
            struct gui_event ev = { 0 };
            ev.type = GUI_EVENT_TIMER;
            post(&win, &ev);
        }
        if (win.repeat_key && now >= win.repeat_due)
        {
            win.repeat_due = now + (win.repeat_rate > 0 ? 1000 / win.repeat_rate : 40);
            key_down(&win, win.repeat_key);
        }
        if (win.frame_pending)
            present(&win);   /* a buffer came back: show what waited */
    }

    gui_app_free(win.app);
    for (int i = 0; i < 2; i++)
        buffer_destroy(&win.buffers[i]);
    font_free(&c->main);
    font_free(&c->small_font);
    FT_Done_FreeType(c->ft);
    free(c->pixels);
    free(c->clip_text);
    if (win.compose) xkb_compose_state_unref(win.compose);
    if (win.compose_table) xkb_compose_table_unref(win.compose_table);
    if (win.xkb_state) xkb_state_unref(win.xkb_state);
    if (win.keymap) xkb_keymap_unref(win.keymap);
    if (win.xkb) xkb_context_unref(win.xkb);
    if (win.cursor_theme) wl_cursor_theme_destroy(win.cursor_theme);
    xdg_toplevel_destroy(win.toplevel);
    xdg_surface_destroy(win.xdg_surface);
    wl_surface_destroy(win.surface);
    wl_display_disconnect(win.display);
    return 0;
}
