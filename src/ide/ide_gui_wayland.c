/* --- Fonts: FreeType, glyphs rendered once and kept --- */

struct glyph
{
    uint32_t cp;
    int left, top;            /* the bitmap's offset from the pen, px (top: above the baseline) */
    int w, h;
    unsigned char* alpha;     /* w * h coverage; NULL: nothing to draw */
};

struct font
{
    FT_Face face;
    struct gui_metrics metrics;
    struct glyph* glyphs;     /* open hashing on cp */
    int cap, count;
};

/* --- The window --- */

struct shm_buffer
{
    struct wl_buffer* buffer;
    uint32_t* pixels;
    int w, h;
    size_t size;
    int busy;                    /* the compositor still reads it */
    struct gui_rect stale;       /* what changed in the canvas since it was filled */
};

struct gui_canvas
{
    uint32_t* pixels;            /* the back buffer: what the core draws on, XRGB */
    int w, h;
    int clip_on, cx, cy, cw, ch;
    struct font main, small_font;
    FT_Library ft;
    int pt;
    const char* family;          /* NULL: the first installed candidate */
    char* clip_text;             /* what we offer as the selection */
    struct wl_window* win;
};

