/* A keysym as a gui key code, or 0 for keys the framework ignores. */
static int map_keysym(xkb_keysym_t sym)
{
    if (sym >= XKB_KEY_a && sym <= XKB_KEY_z) return (int)(sym - XKB_KEY_a + 'A');
    if (sym >= XKB_KEY_A && sym <= XKB_KEY_Z) return (int)sym;
    if (sym >= XKB_KEY_0 && sym <= XKB_KEY_9) return (int)sym;
    if (sym >= XKB_KEY_F1 && sym <= XKB_KEY_F12) return GUI_KEY_F1 + (int)(sym - XKB_KEY_F1);
    switch (sym)
    {
    case XKB_KEY_Escape: return GUI_KEY_ESCAPE;
    case XKB_KEY_Return: case XKB_KEY_KP_Enter: return GUI_KEY_ENTER;
    case XKB_KEY_Tab: case XKB_KEY_ISO_Left_Tab: return GUI_KEY_TAB;
    case XKB_KEY_BackSpace: return GUI_KEY_BACKSPACE;
    case XKB_KEY_Delete: case XKB_KEY_KP_Delete: return GUI_KEY_DELETE;
    case XKB_KEY_Insert: case XKB_KEY_KP_Insert: return GUI_KEY_INSERT;
    case XKB_KEY_Home: case XKB_KEY_KP_Home: return GUI_KEY_HOME;
    case XKB_KEY_End: case XKB_KEY_KP_End: return GUI_KEY_END;
    case XKB_KEY_Page_Up: case XKB_KEY_KP_Page_Up: return GUI_KEY_PAGEUP;
    case XKB_KEY_Page_Down: case XKB_KEY_KP_Page_Down: return GUI_KEY_PAGEDOWN;
    case XKB_KEY_Left: case XKB_KEY_KP_Left: return GUI_KEY_LEFT;
    case XKB_KEY_Right: case XKB_KEY_KP_Right: return GUI_KEY_RIGHT;
    case XKB_KEY_Up: case XKB_KEY_KP_Up: return GUI_KEY_UP;
    case XKB_KEY_Down: case XKB_KEY_KP_Down: return GUI_KEY_DOWN;
    case XKB_KEY_space: return ' ';
    case XKB_KEY_plus: case XKB_KEY_equal: case XKB_KEY_KP_Add: return '+';
    case XKB_KEY_minus: case XKB_KEY_KP_Subtract: return '-';
    }
    return 0;
}

static uint32_t utf8_decode(const char* s, int* len)
{
    const unsigned char* u = (const unsigned char*)s;
    if (u[0] < 0x80) { *len = 1; return u[0]; }
    if ((u[0] & 0xE0) == 0xC0 && u[1]) { *len = 2; return (uint32_t)(u[0] & 0x1F) << 6 | (u[1] & 0x3F); }
    if ((u[0] & 0xF0) == 0xE0 && u[1] && u[2])
    { *len = 3; return (uint32_t)(u[0] & 0x0F) << 12 | (uint32_t)(u[1] & 0x3F) << 6 | (u[2] & 0x3F); }
    if ((u[0] & 0xF8) == 0xF0 && u[1] && u[2] && u[3])
    {
        *len = 4;
        return (uint32_t)(u[0] & 0x07) << 18 | (uint32_t)(u[1] & 0x3F) << 12 | (uint32_t)(u[2] & 0x3F) << 6 | (u[3] & 0x3F);
    }
    *len = 1;
    return 0;
}

static void post_chars(struct wl_window* win, const char* text)
{
    for (const char* p = text; *p;)
    {
        int len;
        uint32_t ch = utf8_decode(p, &len);
        p += len;
        if (ch < 32 || ch == 127)
            continue;
        struct gui_event ev = { 0 };
        ev.type = GUI_EVENT_CHAR;
        ev.ch = ch;
        post(win, &ev);
    }
}

/* Like X11: a key event for keys and shortcuts, then a char event for what
 * the key types - none with Ctrl or Alt held. `xkb_key` is the evdev code + 8. */
static void key_down(struct wl_window* win, uint32_t xkb_key)
{
    xkb_keysym_t sym = xkb_state_key_get_one_sym(win->xkb_state, xkb_key);
    int mods = current_mods(win);
    int key = map_keysym(xkb_keysym_to_lower(sym) == sym ? sym : xkb_keysym_to_lower(sym));
    if (key)
    {
        struct gui_event ev = { 0 };
        ev.type = GUI_EVENT_KEY;
        ev.key = key;
        ev.mods = mods;
        post(win, &ev);
    }
    if (mods & (GUI_MOD_CTRL | GUI_MOD_ALT))
        return;
    char text[64] = "";
    if (win->compose)
    {
        xkb_compose_state_feed(win->compose, sym);
        switch (xkb_compose_state_get_status(win->compose))
        {
        case XKB_COMPOSE_COMPOSING:
            return;   /* a dead key: wait for the next one */
        case XKB_COMPOSE_COMPOSED:
            xkb_compose_state_get_utf8(win->compose, text, sizeof text);
            xkb_compose_state_reset(win->compose);
            post_chars(win, text);
            return;
        case XKB_COMPOSE_CANCELLED:
            xkb_compose_state_reset(win->compose);
            return;
        default:
            break;
        }
    }
    xkb_state_key_get_utf8(win->xkb_state, xkb_key, text, sizeof text);
    post_chars(win, text);
}

static void keyboard_keymap(void* data, struct wl_keyboard* k, uint32_t format, int32_t fd, uint32_t size)
{
    (void)k;
    struct wl_window* win = data;
    if (format != WL_KEYBOARD_KEYMAP_FORMAT_XKB_V1)
    {
        close(fd);
        return;
    }
    char* map = mmap(NULL, size, PROT_READ, MAP_PRIVATE, fd, 0);
    close(fd);
    if (map == MAP_FAILED)
        return;
    struct xkb_keymap* keymap = xkb_keymap_new_from_string(win->xkb, map, XKB_KEYMAP_FORMAT_TEXT_V1,
                                                           XKB_KEYMAP_COMPILE_NO_FLAGS);
    munmap(map, size);
    if (!keymap)
        return;
    if (win->xkb_state)
        xkb_state_unref(win->xkb_state);
    if (win->keymap)
        xkb_keymap_unref(win->keymap);
    win->keymap = keymap;
    win->xkb_state = xkb_state_new(keymap);
}

