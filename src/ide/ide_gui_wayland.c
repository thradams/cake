static void set_cursor(struct wl_window* win, enum gui_cursor cursor)
{
    if (!win->pointer || !win->cursor_theme || !win->pointer_serial)
        return;
    if (win->cursor_shown && cursor == win->cursor)
        return;
    static const char* const names[][2] = {
        { "left_ptr", "default" }, { "sb_h_double_arrow", "ew-resize" }, { "sb_v_double_arrow", "ns-resize" },
        { "bottom_right_corner", "nwse-resize" }, { "bottom_left_corner", "nesw-resize" },
    };
    struct wl_cursor* wc = wl_cursor_theme_get_cursor(win->cursor_theme, names[cursor][0]);
    if (!wc)
        wc = wl_cursor_theme_get_cursor(win->cursor_theme, names[cursor][1]);
    if (!wc)
        wc = wl_cursor_theme_get_cursor(win->cursor_theme, "left_ptr");
    if (!wc || wc->image_count == 0)
        return;
    struct wl_cursor_image* img = wc->images[0];
    struct wl_buffer* buffer = wl_cursor_image_get_buffer(img);
    wl_pointer_set_cursor(win->pointer, win->pointer_serial, win->cursor_surface,
                          (int32_t)img->hotspot_x, (int32_t)img->hotspot_y);
    wl_surface_attach(win->cursor_surface, buffer, 0, 0);
    wl_surface_damage_buffer(win->cursor_surface, 0, 0, (int32_t)img->width, (int32_t)img->height);
    wl_surface_commit(win->cursor_surface);
    win->cursor = cursor;
    win->cursor_shown = 1;
}

