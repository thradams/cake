static void keyboard_key(void* data, struct wl_keyboard* k, uint32_t serial, uint32_t time, uint32_t key,
                         uint32_t state)
{
    (void)k; (void)time;
    struct wl_window* win = data;
    win->serial = serial;
    if (!win->xkb_state)
        return;
    uint32_t xkb_key = key + 8;
    if (state == WL_KEYBOARD_KEY_STATE_PRESSED)
    {
        key_down(win, xkb_key);
        if (win->repeat_rate > 0 && xkb_keymap_key_repeats(win->keymap, xkb_key))
        {
            win->repeat_key = xkb_key;
            win->repeat_due = now_ms() + win->repeat_delay;
        }
    }
    else if (win->repeat_key == xkb_key)
    {
        win->repeat_key = 0;
    }
}

