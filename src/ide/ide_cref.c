static int cref_compare(const void* key, const void* e)
{
    return strcmp((const char*)key, ((const struct cref_entry*)e)->name);
}

/* The cppreference URL of the standard C name `name` into `url`; 0 if unknown. */
int ide_cref_url(const char* name, char* url, int cap)
{
    const struct cref_entry* e = bsearch(name, cref_table, sizeof cref_table / sizeof cref_table[0],
                                         sizeof cref_table[0], cref_compare);
    if (!e)
        return 0;
    snprintf(url, (size_t)cap, "https://en.cppreference.com/c/%s", e->path);
    return 1;
}
